import { access, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

// DESIGN.md's implementation is the source for both the app and isolated plugin views.
const source = new URL("../src/styles/tokens.css", import.meta.url);
const targets = [
  new URL("../packages/plugin-sdk/src/design.ts", import.meta.url),
  new URL("../../daily-journal-plugin/vendor/plugin-sdk/src/design.ts", import.meta.url),
];
const tokens = (await readFile(source, "utf8"))
  .replaceAll(":root", ":host")
  .replaceAll('html[data-theme="dark"]', ':host([data-daily-theme="dark"])');
const base = `
:host { display: block; color: var(--text); background: var(--app-main-bg); font: 14px/20px var(--font-sans); -webkit-font-smoothing: antialiased; font-variant-numeric: tabular-nums; }
*, *::before, *::after { box-sizing: border-box; }
button, input, textarea, select { font: inherit; color: inherit; letter-spacing: 0; -webkit-app-region: no-drag; }
button { cursor: pointer; }
button, a, input, select, textarea, summary { touch-action: manipulation; }
button, input, select, textarea { transition: color var(--duration-fast) var(--ease-out), background-color var(--duration-fast) var(--ease-out), border-color var(--duration-fast) var(--ease-out); }
:where(button, input, select, textarea, a, summary, [tabindex]):focus-visible { outline: none; box-shadow: var(--focus-ring); }
:where(button, input, select, textarea):disabled { cursor: not-allowed; }
input::placeholder, textarea::placeholder { color: var(--text-muted); opacity: 1; }
.lucide { flex-shrink: 0; stroke-width: 1.75; }
@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after { animation: none !important; transition: none !important; scroll-behavior: auto !important; }
}
`;
const output = `// Generated by scripts/sync-plugin-design.mjs from src/styles/tokens.css.\n// Mount with view.addStyles(pluginDesignStyles) before a plugin's own stylesheet.\nexport const pluginDesignStyles = ${JSON.stringify(tokens + base)};\n`;
for (const target of targets) {
  // The Journal repository vendors the SDK, but is optional in standalone Daily checkouts.
  if (target.pathname.includes("/daily-journal-plugin/") && !await access(new URL(".", target)).then(() => true, () => false)) continue;
  if (process.argv.includes("--check")) {
    if (await readFile(target, "utf8").catch(() => "") !== output) {
      console.error(`Plugin design tokens are stale: ${fileURLToPath(target)}`);
      process.exitCode = 1;
    }
  } else await writeFile(target, output);
}
